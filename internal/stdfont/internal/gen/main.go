// Command gen builds package stdfont's width tables from the Core 14 AFM
// files (Adobe; see ../../NOTICE):
//
//	go run ./internal/stdfont/internal/gen <dir holding the 14 .afm files>
//
// It keeps each glyph's advance width and nothing else. Latin fonts are
// keyed by the text their glyph names spell, through the Adobe Glyph
// List, so a width can be found for a code through whatever encoding a
// font uses; Symbol and ZapfDingbats by code in their built-in encodings.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/giraffesyo/pdf/internal/encoding"
)

// latin are the fonts with distinct Latin metrics; the oblique and italic
// Helvetica share their upright's, and Courier's are all 600.
var latin = []string{"Helvetica", "Helvetica-Bold", "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"}

type glyph struct {
	code  int
	width int
	name  string
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gen <dir holding the Core 14 .afm files>")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from the Core 14 AFM files; DO NOT EDIT.\n")
	b.WriteString("// Modified from the AFM files: only advance widths are kept (see NOTICE).\n\n")
	b.WriteString("package stdfont\n\n")
	b.WriteString("var latinWidths = map[string]map[string]uint16{\n")
	for _, name := range latin {
		glyphs, err := read(filepath.Join(os.Args[1], name+".afm"))
		if err != nil {
			log.Fatal(err)
		}
		byText := map[string]int{}
		for _, g := range glyphs {
			if text := encoding.GlyphToText(g.name); text != "" {
				if _, seen := byText[text]; !seen {
					byText[text] = g.width
				}
			}
		}
		keys := make([]string, 0, len(byText))
		for k := range byText {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		fmt.Fprintf(&b, "%q: {", name)
		for _, k := range keys {
			fmt.Fprintf(&b, "%q: %d, ", k, byText[k])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	for _, name := range []string{"Symbol", "ZapfDingbats"} {
		glyphs, err := read(filepath.Join(os.Args[1], name+".afm"))
		if err != nil {
			log.Fatal(err)
		}
		var widths [256]int
		for _, g := range glyphs {
			if g.code >= 0 && g.code < 256 {
				widths[g.code] = g.width
			}
		}
		fmt.Fprintf(&b, "var %sWidths = [256]uint16{", strings.ToLower(name[:1])+name[1:])
		for code, w := range widths {
			if w != 0 {
				fmt.Fprintf(&b, "%d: %d, ", code, w)
			}
		}
		b.WriteString("}\n\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join("internal", "stdfont", "widths.go"), src, 0o600); err != nil {
		log.Fatal(err)
	}
}

// read returns an AFM file's character metrics: "C code ; WX width ; N name ; …".
func read(path string) ([]glyph, error) {
	f, err := os.Open(path) //nolint:gosec // the AFM directory is the command's argument
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	var glyphs []glyph
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if !strings.HasPrefix(line, "C ") {
			continue
		}
		g := glyph{code: -1}
		for _, part := range strings.Split(line, ";") {
			fields := strings.Fields(part)
			if len(fields) != 2 {
				continue
			}
			switch fields[0] {
			case "C":
				g.code, _ = strconv.Atoi(fields[1])
			case "WX":
				g.width, _ = strconv.Atoi(fields[1])
			case "N":
				g.name = fields[1]
			}
		}
		glyphs = append(glyphs, g)
	}
	return glyphs, sc.Err()
}
